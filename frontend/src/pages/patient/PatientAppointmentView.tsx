import React, { useMemo, useState, useRef } from 'react';
import {
  CalendarPlus, MapPin, Star, Sparkles, Search, ChevronRight, ExternalLink,
  Clock, Stethoscope, CheckCircle2, ArrowLeft, Bot, Filter, LocateFixed, Navigation2,
  Download, FileText, IndianRupee, CalendarClock, Camera, User,
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import {
  CITIES, PURPOSE_LABELS, SORT_OPTIONS, rankHospitalsByProblem, getAvailableSlots,
  CityZone, AppointmentPurpose, HospitalInfo, HospitalDoctor, HospitalSortMode, UserCoords,
} from '../../data/hospitals';
import { AgeGroup, AppointmentCriticality, PatientAppointment } from '../../types';
import { downloadPdf } from '../../utils/prescriptionPdf';

interface Props { onSuccess?: () => void; onCancel?: () => void; }
type Step = 'search' | 'hospital' | 'doctor' | 'slot' | 'confirm' | 'done';

const STEPS: Step[] = ['search', 'hospital', 'doctor', 'slot', 'confirm'];
const STEP_LABEL: Record<Step, string> = {
  search: 'Search', hospital: 'Hospital', doctor: 'Doctor', slot: 'Slot', confirm: 'Confirm', done: 'Done',
};

const AGE_GROUPS: AgeGroup[] = ['0-12', '13-17', '18-40', '41-60', '60+'];

function tomorrowISO() {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  return d.toISOString().slice(0, 10);
}

function formatTime12(t: string) {
  const [hStr, m] = t.split(':');
  let h = parseInt(hStr, 10);
  const ampm = h >= 12 ? 'PM' : 'AM';
  h = h % 12;
  if (h === 0) h = 12;
  return `${h}:${m} ${ampm}`;
}

function downloadPrescriptionPdf(a: PatientAppointment) {
  const meds = a.prescription?.medicines ?? [];
  const lines = [
    'RHEON AI — Official Prescription',
    '================================',
    `Appointment ID: ${a.id}`,
    `Patient: ${a.patient_name}  |  Age group: ${a.patient_age_group}`,
    `Doctor: ${a.doctor_name}  ·  ${a.doctor_specialty}`,
    `Hospital: ${a.hospital_name} (${a.hospital_city})`,
    `Visit: ${a.date}  ${formatTime12(a.time)}`,
    `Status: ${a.status}  |  Priority: ${a.criticality}`,
    '',
    'Medicines',
    '---------',
    ...(meds.length
      ? meds.map((m, i) => `${i + 1}. ${m.name}  |  ${m.dosage}  |  ${m.duration}`)
      : ['(Prescription pending — doctor has not completed the visit yet)']),
    '',
    `Clinical advice: ${a.prescription?.advice ?? 'Follow treating physician instructions.'}`,
    '',
    `Total bill: INR ${a.total_bill_inr.toLocaleString('en-IN')}`,
    a.reappointment_date
      ? `Re-appointment: ${a.reappointment_date} ${a.reappointment_time ? formatTime12(a.reappointment_time) : ''} — ${a.reappointment_note || ''}`
      : 'Re-appointment: not allotted yet',
    '',
    `Issued: ${a.prescription?.issued_at ?? a.created_at}`,
    'Generated by RHEON AI Care · Delhi NCR',
  ];
  downloadPdf(`prescription-${a.id}.pdf`, lines);
}

export const PatientAppointmentView: React.FC<Props> = ({ onSuccess, onCancel }) => {
  const { user, addAppointment, bookedSlotKeys, appointments, slotOccupancy } = useAuth();
  const [step, setStep] = useState<Step>('search');
  const [problem, setProblem] = useState('');
  const [city, setCity] = useState<CityZone | 'ALL'>('ALL');
  const [purpose, setPurpose] = useState<AppointmentPurpose>('consultation');
  const [ageGroup, setAgeGroup] = useState<AgeGroup>('18-40');
  const [patientPhoto, setPatientPhoto] = useState<string | undefined>();
  const photoRef = useRef<HTMLInputElement>(null);
  const [userCoords, setUserCoords] = useState<UserCoords | null>(null);
  const [locStatus, setLocStatus] = useState<'idle' | 'loading' | 'ok' | 'denied' | 'error'>('idle');
  const [locLabel, setLocLabel] = useState('');
  const [sortMode, setSortMode] = useState<HospitalSortMode>('best_match');
  const [selectedHospital, setSelectedHospital] = useState<(HospitalInfo & { effectiveDistanceKm?: number; avgRating?: number }) | null>(null);
  const [selectedDoctor, setSelectedDoctor] = useState<HospitalDoctor | null>(null);
  const [selectedDate, setSelectedDate] = useState(tomorrowISO());
  const [selectedTime, setSelectedTime] = useState<string | null>(null);
  const [criticality, setCriticality] = useState<AppointmentCriticality>('ROUTINE');
  const [agentThinking, setAgentThinking] = useState(false);
  const [bookedId, setBookedId] = useState<string | null>(null);
  const [expandedAppt, setExpandedAppt] = useState<string | null>(null);
  const [historyFilter, setHistoryFilter] = useState<'ALL' | 'BOOKED' | 'CONFIRMED' | 'COMPLETED' | 'CANCELLED' | 'FOLLOW_UP'>('ALL');

  const ranked = useMemo(
    () => rankHospitalsByProblem(problem, city, userCoords, sortMode),
    [problem, city, userCoords, sortMode]
  );
  const slots = useMemo(() => {
    if (!selectedDoctor) return [];
    return getAvailableSlots(selectedDoctor.id, selectedDate, bookedSlotKeys).map((s) => {
      const occ = slotOccupancy(selectedDoctor.id, selectedDate, s.time);
      return { ...s, occupancy: occ, isRed: occ >= 1 };
    });
  }, [selectedDoctor, selectedDate, bookedSlotKeys, slotOccupancy]);

  const myAppointments = useMemo(() => {
    const mine = appointments.filter((a) => a.patient_email === user?.email || a.patient_name === user?.name);
    if (historyFilter === 'ALL') return mine;
    if (historyFilter === 'FOLLOW_UP') return mine.filter((a) => !!a.reappointment_date && a.status !== 'CANCELLED');
    return mine.filter((a) => a.status === historyFilter);
  }, [appointments, user, historyFilter]);

  const historyCounts = useMemo(() => {
    const mine = appointments.filter((a) => a.patient_email === user?.email || a.patient_name === user?.name);
    return {
      ALL: mine.length,
      BOOKED: mine.filter((a) => a.status === 'BOOKED').length,
      CONFIRMED: mine.filter((a) => a.status === 'CONFIRMED').length,
      COMPLETED: mine.filter((a) => a.status === 'COMPLETED').length,
      CANCELLED: mine.filter((a) => a.status === 'CANCELLED').length,
      FOLLOW_UP: mine.filter((a) => !!a.reappointment_date && a.status !== 'CANCELLED').length,
    };
  }, [appointments, user]);

  const stepIndex = STEPS.indexOf(step === 'done' ? 'confirm' : step);

  const canGoToStep = (target: Step) => {
    if (target === 'search') return true;
    if (target === 'hospital') return true; // after search always allowed once ranked once - allow free nav backward
    if (target === 'doctor') return !!selectedHospital;
    if (target === 'slot') return !!selectedHospital && !!selectedDoctor;
    if (target === 'confirm') return !!selectedHospital && !!selectedDoctor && !!selectedTime;
    return false;
  };

  const goToStep = (target: Step) => {
    if (target === step) return;
    const ti = STEPS.indexOf(target);
    // Always allow going back
    if (ti < stepIndex) {
      setStep(target);
      return;
    }
    // Forward only if prerequisites met
    if (canGoToStep(target)) setStep(target);
  };

  const requestLocation = () => {
    if (!navigator.geolocation) {
      setLocStatus('error');
      setLocLabel('Geolocation not supported in this browser');
      return;
    }
    setLocStatus('loading');
    navigator.geolocation.getCurrentPosition(
      (pos) => {
        const coords = { lat: pos.coords.latitude, lng: pos.coords.longitude };
        setUserCoords(coords);
        setLocStatus('ok');
        setLocLabel(`${coords.lat.toFixed(4)}°, ${coords.lng.toFixed(4)}° · ±${Math.round(pos.coords.accuracy || 0)} m`);
        setSortMode('nearest');
      },
      (err) => {
        if (err.code === err.PERMISSION_DENIED) {
          setLocStatus('denied');
          setLocLabel('Location permission denied — enable it in browser settings');
        } else {
          setLocStatus('error');
          setLocLabel(err.message || 'Could not read location');
        }
      },
      { enableHighAccuracy: true, timeout: 12000, maximumAge: 60000 }
    );
  };

  const clearLocation = () => {
    setUserCoords(null);
    setLocStatus('idle');
    setLocLabel('');
  };

  const onPhotoChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    if (file.size > 2_000_000) {
      alert('Please choose an image under 2 MB');
      return;
    }
    const reader = new FileReader();
    reader.onload = () => setPatientPhoto(typeof reader.result === 'string' ? reader.result : undefined);
    reader.readAsDataURL(file);
  };

  const runAgentMatch = async () => {
    setAgentThinking(true);
    await new Promise((r) => setTimeout(r, 700));
    setAgentThinking(false);
    setStep('hospital');
  };

  const confirmBooking = () => {
    if (!selectedHospital || !selectedDoctor || !selectedTime || !user) return;
    const id = `APT-${Date.now().toString().slice(-6)}`;
    // Demo prescription + bill for completed path (available once doctor "completes" — pre-seed light demo data on confirm for history UX)
    const appt: PatientAppointment = {
      id,
      patient_name: user.name,
      patient_email: user.email,
      patient_age_group: ageGroup,
      patient_photo: patientPhoto,
      hospital_id: selectedHospital.id,
      hospital_name: selectedHospital.name,
      hospital_city: selectedHospital.city,
      hospital_map_url: selectedHospital.mapUrl,
      doctor_id: selectedDoctor.id,
      doctor_name: selectedDoctor.name,
      doctor_specialty: selectedDoctor.specialty,
      purpose,
      purpose_label: PURPOSE_LABELS[purpose],
      problem_description: problem || 'General consultation',
      date: selectedDate,
      time: selectedTime,
      status: 'BOOKED',
      criticality,
      is_emergency_slot: false,
      agent_note: `RHEON Agent AI ranked ${selectedHospital.name} for "${problem || purpose}" · ${selectedHospital.effectiveDistanceKm != null ? selectedHospital.effectiveDistanceKm + ' km' : ''} ${userCoords ? 'from your GPS' : '(NCR ref)'} · slot ${formatTime12(selectedTime)} auto-reserved.`,
      created_at: new Date().toLocaleString('en-IN', { hour12: true }),
      total_bill_inr: criticality === 'CRITICAL' ? 3500 : criticality === 'PRIORITY' ? 2200 : 1200,
      prescription: undefined,
      reappointment_date: undefined,
    };
    addAppointment(appt);
    setBookedId(id);
    setStep('done');
    onSuccess?.();
  };

  return (
    <div className="flex flex-col gap-6 max-w-6xl mx-auto">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-xl md:text-2xl font-bold text-ink-primary tracking-tight">Book Appointment</h1>
            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-teal-brand/10 text-teal-brand border border-teal-brand/20">
              <Bot className="w-3 h-3" /> Agent AI Scheduling
            </span>
          </div>
          <p className="text-xs md:text-sm text-ink-secondary mt-0.5">
            Describe your need — RHEON Agent ranks hospitals by specialty fit and distance, then opens live doctor slots.
          </p>
        </div>
        {onCancel && step !== 'done' && (
          <button onClick={onCancel} className="text-xs font-semibold text-ink-secondary hover:text-teal-brand flex items-center gap-1">
            <ArrowLeft className="w-3.5 h-3.5" /> Back
          </button>
        )}
      </div>

      <div className="rounded-2xl border border-teal-brand/20 bg-gradient-to-r from-teal-brand/5 to-pastel-mint-bg px-4 py-3 flex items-start gap-3">
        <div className="w-9 h-9 rounded-xl bg-teal-brand text-white flex items-center justify-center shrink-0 shadow-pill">
          <Sparkles className="w-4 h-4" />
        </div>
        <div className="min-w-0">
          <p className="text-xs font-bold text-ink-primary">Not manual booking — Agent AI orchestration</p>
          <p className="text-[11px] text-ink-secondary mt-0.5 leading-relaxed">
            The scheduling agent scores each hospital on specialty relevance, NCR distance, and live slot availability. Booked slots lock so the medical officer dashboard always reflects truth.
          </p>
        </div>
      </div>

      {/* Clickable step navigator */}
      {step !== 'done' && (
        <div className="flex flex-wrap items-center gap-1.5 text-[10px] font-bold uppercase tracking-wider">
          {STEPS.map((s, i) => {
            const active = step === s;
            const past = i < stepIndex;
            const allowed = canGoToStep(s) || past || active;
            return (
              <React.Fragment key={s}>
                <button
                  type="button"
                  disabled={!allowed}
                  onClick={() => goToStep(s)}
                  className={`px-2.5 py-1 rounded-full border transition-all ${
                    active
                      ? 'bg-teal-brand text-white border-teal-brand shadow-pill'
                      : past
                      ? 'bg-white text-teal-brand border-teal-brand/40 hover:bg-teal-brand/5 cursor-pointer'
                      : allowed
                      ? 'bg-white text-ink-secondary border-shell-border hover:border-teal-brand/40 cursor-pointer'
                      : 'bg-shell-bg text-ink-secondary/40 border-shell-border cursor-not-allowed'
                  }`}
                  title={allowed ? `Go to ${STEP_LABEL[s]}` : 'Complete previous steps first'}
                >
                  {i + 1}. {STEP_LABEL[s]}
                </button>
                {i < STEPS.length - 1 && <ChevronRight className="w-3 h-3 opacity-40 text-ink-secondary" />}
              </React.Fragment>
            );
          })}
        </div>
      )}

      {step === 'search' && (
        <div className="bg-white rounded-3xl border border-shell-border shadow-card p-5 md:p-6 flex flex-col gap-4">
          <div>
            <label className="block text-xs font-bold text-ink-secondary mb-1.5 uppercase tracking-wider">What do you need help with?</label>
            <div className="relative">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-ink-secondary" />
              <input value={problem} onChange={(e) => setProblem(e.target.value)}
                placeholder="e.g. chest pain, blood sample test, pregnancy checkup, eye cataract…"
                className="w-full pl-10 pr-4 py-3 bg-shell-bg border border-shell-border rounded-2xl text-sm text-ink-primary focus:outline-none focus:ring-2 focus:ring-teal-brand/20 focus:border-teal-brand" />
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            <div>
              <label className="block text-xs font-bold text-ink-secondary mb-1.5 uppercase tracking-wider">Appointment type</label>
              <select value={purpose} onChange={(e) => setPurpose(e.target.value as AppointmentPurpose)}
                className="w-full px-3.5 py-2.5 bg-shell-bg border border-shell-border rounded-xl text-sm font-semibold text-ink-primary focus:outline-none focus:border-teal-brand">
                {(Object.keys(PURPOSE_LABELS) as AppointmentPurpose[]).map((k) => (
                  <option key={k} value={k}>{PURPOSE_LABELS[k]}</option>
                ))}
              </select>
            </div>
            <div>
              <label className="block text-xs font-bold text-ink-secondary mb-1.5 uppercase tracking-wider flex items-center gap-1">
                <Filter className="w-3 h-3" /> City filter
              </label>
              <select value={city} onChange={(e) => setCity(e.target.value as CityZone | 'ALL')}
                className="w-full px-3.5 py-2.5 bg-shell-bg border border-shell-border rounded-xl text-sm font-semibold text-ink-primary focus:outline-none focus:border-teal-brand">
                {CITIES.map((c) => (<option key={c} value={c}>{c === 'ALL' ? 'All NCR cities' : c}</option>))}
              </select>
            </div>
            <div>
              <label className="block text-xs font-bold text-ink-secondary mb-1.5 uppercase tracking-wider">Age group</label>
              <select value={ageGroup} onChange={(e) => setAgeGroup(e.target.value as AgeGroup)}
                className="w-full px-3.5 py-2.5 bg-shell-bg border border-shell-border rounded-xl text-sm font-semibold text-ink-primary focus:outline-none focus:border-teal-brand">
                {AGE_GROUPS.map((g) => (<option key={g} value={g}>{g} years</option>))}
              </select>
            </div>
          </div>

          {/* Patient photo */}
          <div className="flex flex-col sm:flex-row sm:items-center gap-3 rounded-2xl border border-shell-border bg-shell-bg/50 p-3.5">
            <div className="w-14 h-14 rounded-2xl overflow-hidden bg-white border border-shell-border flex items-center justify-center shrink-0">
              {patientPhoto ? (
                <img src={patientPhoto} alt="Patient" className="w-full h-full object-cover" />
              ) : (
                <User className="w-6 h-6 text-ink-secondary/50" />
              )}
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-xs font-bold text-ink-primary">Patient photo</p>
              <p className="text-[11px] text-ink-secondary">Shown on your appointment card and the medical officer dashboard.</p>
            </div>
            <input ref={photoRef} type="file" accept="image/*" className="hidden" onChange={onPhotoChange} />
            <button type="button" onClick={() => photoRef.current?.click()}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-full text-xs font-semibold bg-white border border-shell-border text-ink-primary hover:border-teal-brand">
              <Camera className="w-3.5 h-3.5" /> {patientPhoto ? 'Change photo' : 'Upload photo'}
            </button>
            {patientPhoto && (
              <button type="button" onClick={() => setPatientPhoto(undefined)} className="text-[10px] font-bold text-crimson">Remove</button>
            )}
          </div>

          <div className="rounded-2xl border border-shell-border bg-shell-bg/60 p-3.5 flex flex-col sm:flex-row sm:items-center gap-3">
            <div className="flex-1 min-w-0">
              <p className="text-xs font-bold text-ink-primary flex items-center gap-1.5">
                <LocateFixed className="w-3.5 h-3.5 text-teal-brand" /> Use my current location
              </p>
              <p className="text-[11px] text-ink-secondary mt-0.5">
                {locStatus === 'ok' ? `Location locked · ${locLabel}`
                  : locStatus === 'loading' ? 'Requesting precise GPS…'
                  : locStatus === 'denied' || locStatus === 'error' ? locLabel
                  : 'Agent AI will rank by real distance from you (browser permission only — nothing sent to a server).'}
              </p>
            </div>
            <div className="flex items-center gap-2 shrink-0">
              {userCoords && (
                <button type="button" onClick={clearLocation} className="px-3 py-1.5 rounded-full text-[10px] font-bold border border-shell-border text-ink-secondary hover:text-crimson">Clear</button>
              )}
              <button type="button" onClick={requestLocation} disabled={locStatus === 'loading'}
                className={`inline-flex items-center gap-1.5 px-3.5 py-2 rounded-full text-xs font-semibold transition-all ${
                  userCoords ? 'bg-pastel-mint-bg text-pastel-mint-text border border-pastel-mint-border'
                    : 'bg-teal-brand text-white shadow-pill hover:bg-teal-brand-hover'
                } disabled:opacity-60`}>
                <Navigation2 className={`w-3.5 h-3.5 ${locStatus === 'loading' ? 'animate-pulse' : ''}`} />
                {userCoords ? 'Location on' : locStatus === 'loading' ? 'Locating…' : 'Use my location'}
              </button>
            </div>
          </div>

          <button onClick={runAgentMatch} disabled={agentThinking}
            className="mt-1 w-full sm:w-auto self-start flex items-center justify-center gap-2 px-6 py-3 bg-teal-brand hover:bg-teal-brand-hover text-white rounded-full text-sm font-semibold shadow-pill transition-all disabled:opacity-60">
            {agentThinking ? (<><Sparkles className="w-4 h-4 animate-pulse" /> Agent AI ranking hospitals…</>) : (<><Bot className="w-4 h-4" /> Run Agent Match</>)}
          </button>
        </div>
      )}

      {step === 'hospital' && (
        <div className="flex flex-col gap-4">
          <div className="flex flex-col gap-3">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
              <p className="text-xs text-ink-secondary">
                <span className="font-bold text-teal-brand">{ranked.length}</span> hospitals ranked
                {problem ? <> for “<span className="font-semibold text-ink-primary">{problem}</span>”</> : null}
                {userCoords ? <span className="text-teal-brand font-semibold"> · using your GPS</span> : null}
              </p>
              <button onClick={() => setStep('search')} className="text-xs font-semibold text-teal-brand self-start">Refine search</button>
            </div>
            <div className="flex flex-wrap items-center gap-1.5">
              <span className="text-[10px] font-bold text-ink-secondary uppercase tracking-wider mr-1">Sort</span>
              {SORT_OPTIONS.map((opt) => (
                <button key={opt.id} type="button" onClick={() => setSortMode(opt.id)}
                  className={`px-3 py-1.5 rounded-full text-[10px] font-bold border transition-colors ${
                    sortMode === opt.id ? 'bg-teal-brand text-white border-teal-brand shadow-pill' : 'bg-white text-ink-secondary border-shell-border hover:border-teal-brand/40'
                  }`}>{opt.label}</button>
              ))}
            </div>
          </div>
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {ranked.map((h, idx) => (
              <button key={h.id} onClick={() => { setSelectedHospital(h); setSelectedDoctor(null); setSelectedTime(null); setStep('doctor'); }}
                className="text-left bg-white rounded-3xl border border-shell-border shadow-card p-5 hover:border-teal-brand/40 hover:shadow-lg transition-all group">
                <div className="flex items-start justify-between gap-2 mb-3">
                  <div className="min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      {idx < 3 && (
                        <span className="text-[9px] font-bold px-1.5 py-0.5 rounded-full bg-pastel-mint-bg text-pastel-mint-text border border-pastel-mint-border">
                          {sortMode === 'nearest' ? 'NEAREST' : sortMode === 'rating' ? 'TOP RATED' : 'TOP MATCH'}
                        </span>
                      )}
                      <span className="text-[10px] font-bold text-ink-secondary uppercase tracking-wider">{h.city}</span>
                    </div>
                    <h3 className="text-sm font-bold text-ink-primary mt-1 group-hover:text-teal-brand transition-colors">{h.name}</h3>
                    <p className="text-[11px] text-ink-secondary mt-0.5 flex items-center gap-1">
                      <MapPin className="w-3 h-3 shrink-0" />{h.addressShort} · {h.effectiveDistanceKm} km{userCoords ? ' from you' : ''}
                    </p>
                  </div>
                  <a href={h.mapUrl} target="_blank" rel="noopener noreferrer" onClick={(e) => e.stopPropagation()}
                    className="p-2 rounded-xl bg-shell-bg border border-shell-border text-teal-brand hover:bg-teal-brand hover:text-white transition-colors shrink-0" title="Open map">
                    <ExternalLink className="w-3.5 h-3.5" />
                  </a>
                </div>
                <p className="text-[11px] text-ink-secondary leading-relaxed mb-3 line-clamp-2">{h.famousFor}</p>
                <div className="flex flex-wrap gap-1.5 mb-3">
                  {h.specialties.slice(0, 4).map((s) => (
                    <span key={s} className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-shell-bg border border-shell-border text-ink-primary">{s}</span>
                  ))}
                </div>
                <div className="flex items-center justify-between pt-3 border-t border-shell-border/60">
                  <span className="text-[10px] font-medium text-teal-brand flex items-center gap-1"><Bot className="w-3 h-3" />{h.matchReason}</span>
                  <span className="text-[10px] font-bold text-ink-secondary">{h.avgRating}★ · {h.doctors.length} doctors</span>
                </div>
              </button>
            ))}
          </div>
        </div>
      )}

      {step === 'doctor' && selectedHospital && (
        <div className="flex flex-col gap-4">
          <button onClick={() => setStep('hospital')} className="text-xs font-semibold text-teal-brand flex items-center gap-1 self-start">
            <ArrowLeft className="w-3.5 h-3.5" /> Back to hospitals
          </button>
          <div className="bg-white rounded-3xl border border-shell-border shadow-card p-5">
            <div className="mb-4">
              <h2 className="text-base font-bold text-ink-primary">{selectedHospital.name}</h2>
              <p className="text-[11px] text-ink-secondary flex items-center gap-1 mt-0.5">
                <MapPin className="w-3 h-3" />{selectedHospital.city} ·{' '}
                <a href={selectedHospital.mapUrl} target="_blank" rel="noopener noreferrer" className="text-teal-brand font-semibold hover:underline">View on map</a>
              </p>
            </div>
            <p className="text-xs font-bold text-ink-secondary uppercase tracking-wider mb-3 flex items-center gap-1">
              <Stethoscope className="w-3.5 h-3.5" /> Select doctor — Agent shows live availability next
            </p>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {selectedHospital.doctors.map((doc) => (
                <button key={doc.id} onClick={() => { setSelectedDoctor(doc); setSelectedTime(null); setStep('slot'); }}
                  className="text-left p-4 rounded-2xl border border-shell-border bg-shell-card-subtle hover:border-teal-brand/40 hover:bg-white transition-all">
                  <div className="flex items-center gap-3">
                    <div className="w-10 h-10 rounded-full bg-teal-brand/10 border border-teal-brand/20 flex items-center justify-center text-teal-brand font-bold text-xs shrink-0">
                      {doc.name.split(' ').slice(-2).map((p) => p[0]).join('')}
                    </div>
                    <div className="min-w-0">
                      <p className="text-sm font-bold text-ink-primary truncate">{doc.name}</p>
                      <p className="text-[11px] text-ink-secondary">{doc.specialty}</p>
                      <div className="flex items-center gap-2 mt-0.5">
                        <span className="text-[10px] font-semibold text-amber-600 flex items-center gap-0.5">
                          <Star className="w-3 h-3 fill-amber-500 text-amber-500" />{doc.rating}
                        </span>
                        <span className="text-[10px] text-ink-secondary">{doc.experienceYears} yrs exp</span>
                      </div>
                    </div>
                  </div>
                </button>
              ))}
            </div>
          </div>
        </div>
      )}

      {step === 'slot' && selectedHospital && selectedDoctor && (
        <div className="flex flex-col gap-4">
          <button onClick={() => setStep('doctor')} className="text-xs font-semibold text-teal-brand flex items-center gap-1 self-start">
            <ArrowLeft className="w-3.5 h-3.5" /> Back to doctors
          </button>
          <div className="bg-white rounded-3xl border border-shell-border shadow-card p-5 md:p-6">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4 pb-4 border-b border-shell-border/60">
              <div>
                <h2 className="text-base font-bold text-ink-primary">{selectedDoctor.name}</h2>
                <p className="text-[11px] text-ink-secondary">{selectedDoctor.specialty} · {selectedHospital.name}</p>
              </div>
              <div className="flex items-center gap-2">
                <label className="text-[10px] font-bold text-ink-secondary uppercase">Date</label>
                <input type="date" value={selectedDate} min={tomorrowISO()}
                  onChange={(e) => { setSelectedDate(e.target.value); setSelectedTime(null); }}
                  className="px-3 py-1.5 bg-shell-bg border border-shell-border rounded-xl text-xs font-semibold text-ink-primary focus:outline-none focus:border-teal-brand" />
              </div>
            </div>
            <div className="flex flex-wrap items-center gap-2 mb-3">
              <Bot className="w-4 h-4 text-teal-brand" />
              <p className="text-xs font-bold text-ink-primary">Agent AI live slots (12-hour)</p>
              <span className="text-[10px] text-ink-secondary">· green free · red booked</span>
            </div>
            <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-4 lg:grid-cols-7 gap-2">
              {slots.map((s) => {
                const booked = s.isRed || !s.available;
                return (
                  <button key={s.time} disabled={booked}
                    onClick={() => { setSelectedTime(s.time); setStep('confirm'); }}
                    className={`px-2 py-2.5 rounded-xl text-xs font-bold border transition-all ${
                      booked
                        ? 'bg-red-50 text-red-600 border-red-200 cursor-not-allowed line-through'
                        : selectedTime === s.time
                        ? 'bg-teal-brand text-white border-teal-brand shadow-pill'
                        : 'bg-emerald-50 text-emerald-800 border-emerald-200 hover:border-teal-brand hover:text-teal-brand'
                    }`}>
                    {formatTime12(s.time)}
                  </button>
                );
              })}
            </div>
          </div>
        </div>
      )}

      {step === 'confirm' && selectedHospital && selectedDoctor && selectedTime && (
        <div className="bg-white rounded-3xl border border-shell-border shadow-card p-5 md:p-6 max-w-lg">
          <h2 className="text-base font-bold text-ink-primary mb-4 flex items-center gap-2">
            <CalendarPlus className="w-5 h-5 text-teal-brand" /> Confirm appointment
          </h2>
          <div className="flex items-center gap-3 mb-4">
            <div className="w-12 h-12 rounded-2xl overflow-hidden bg-shell-bg border border-shell-border flex items-center justify-center">
              {patientPhoto ? <img src={patientPhoto} alt="" className="w-full h-full object-cover" /> : <User className="w-5 h-5 text-ink-secondary" />}
            </div>
            <div>
              <p className="text-sm font-bold text-ink-primary">{user?.name}</p>
              <p className="text-[11px] text-ink-secondary">Age group {ageGroup}</p>
            </div>
          </div>
          <dl className="space-y-2.5 text-sm mb-5">
            <div className="flex justify-between gap-4"><dt className="text-ink-secondary text-xs">Hospital</dt><dd className="font-semibold text-ink-primary text-right text-xs">{selectedHospital.name}</dd></div>
            <div className="flex justify-between gap-4"><dt className="text-ink-secondary text-xs">Doctor</dt><dd className="font-semibold text-ink-primary text-right text-xs">{selectedDoctor.name} · {selectedDoctor.specialty}</dd></div>
            <div className="flex justify-between gap-4"><dt className="text-ink-secondary text-xs">When</dt><dd className="font-semibold text-ink-primary text-right text-xs flex items-center gap-1"><Clock className="w-3 h-3" />{selectedDate} · {formatTime12(selectedTime)}</dd></div>
            <div className="flex justify-between gap-4"><dt className="text-ink-secondary text-xs">Purpose</dt><dd className="font-semibold text-ink-primary text-right text-xs">{PURPOSE_LABELS[purpose]}</dd></div>
          </dl>
          <div className="mb-4">
            <label className="block text-[10px] font-bold text-ink-secondary uppercase mb-1.5">Priority for medical officer</label>
            <div className="flex flex-wrap gap-1.5">
              {([
                { id: 'ROUTINE' as const, label: 'Routine', cls: 'bg-emerald-50 text-emerald-800 border-emerald-200' },
                { id: 'PRIORITY' as const, label: 'Priority', cls: 'bg-sky-50 text-sky-800 border-sky-200' },
                { id: 'CRITICAL' as const, label: 'Critical', cls: 'bg-red-50 text-red-700 border-red-200' },
              ]).map((c) => (
                <button key={c.id} type="button" onClick={() => setCriticality(c.id)}
                  className={`px-3 py-1.5 rounded-full text-[10px] font-bold border ${criticality === c.id ? c.cls + ' ring-2 ring-offset-1 ring-teal-brand/30' : 'bg-white border-shell-border text-ink-secondary'}`}>
                  {c.label}
                </button>
              ))}
            </div>
          </div>
          <div className="flex flex-wrap gap-2">
            <button onClick={confirmBooking} className="flex items-center gap-2 px-5 py-2.5 bg-teal-brand hover:bg-teal-brand-hover text-white rounded-full text-sm font-semibold shadow-pill">
              <CheckCircle2 className="w-4 h-4" /> Confirm booking
            </button>
            <button onClick={() => setStep('slot')} className="px-4 py-2.5 text-sm font-semibold text-ink-secondary hover:text-ink-primary">Change slot</button>
          </div>
        </div>
      )}

      {step === 'done' && (
        <div className="bg-white rounded-3xl border border-shell-border shadow-card p-8 text-center max-w-md mx-auto">
          <div className="w-14 h-14 rounded-full bg-pastel-mint-bg border border-pastel-mint-border flex items-center justify-center mx-auto mb-4">
            <CheckCircle2 className="w-7 h-7 text-emerald-600" />
          </div>
          <h2 className="text-lg font-bold text-ink-primary">Appointment booked</h2>
          <p className="text-xs text-ink-secondary mt-1 mb-4">
            ID <span className="font-mono font-bold text-teal-brand">{bookedId}</span> — visible to Medical Officer under Appointments.
          </p>
          <button onClick={() => { setStep('search'); setSelectedHospital(null); setSelectedDoctor(null); setSelectedTime(null); setProblem(''); }}
            className="text-sm font-semibold text-teal-brand hover:underline">Book another</button>
        </div>
      )}

      {/* Appointment history with prescription / bill / reappointment */}
      {step === 'search' && (
        <div className="bg-white rounded-3xl border border-shell-border shadow-card p-5">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-3">
            <h3 className="text-sm font-bold text-ink-primary">Your appointments</h3>
            <div className="flex flex-wrap gap-1.5">
              {([
                { id: 'ALL' as const, label: 'All' },
                { id: 'BOOKED' as const, label: 'Booked' },
                { id: 'CONFIRMED' as const, label: 'Confirmed' },
                { id: 'COMPLETED' as const, label: 'Completed' },
                { id: 'FOLLOW_UP' as const, label: 'Follow-up' },
                { id: 'CANCELLED' as const, label: 'Cancelled' },
              ]).map((f) => (
                <button key={f.id} type="button" onClick={() => setHistoryFilter(f.id)}
                  className={`px-2.5 py-1 rounded-full text-[10px] font-bold border transition-colors ${
                    historyFilter === f.id
                      ? f.id === 'CANCELLED' ? 'bg-red-600 text-white border-red-600' : 'bg-teal-brand text-white border-teal-brand'
                      : 'bg-white text-ink-secondary border-shell-border hover:border-teal-brand/40'
                  }`}>
                  {f.label}{historyCounts[f.id] != null ? ` (${historyCounts[f.id]})` : ''}
                </button>
              ))}
            </div>
          </div>
          {myAppointments.length === 0 ? (
            <p className="text-xs text-ink-secondary py-6 text-center">No appointments in this filter.</p>
          ) : (
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            {myAppointments.map((a) => {
              const cancelled = a.status === 'CANCELLED';
              const open = expandedAppt === a.id;
              return (
                <div key={a.id}
                  className={`rounded-2xl border p-3.5 flex flex-col gap-1.5 ${
                    cancelled
                      ? 'bg-red-50/80 border-red-200'
                      : 'border-shell-border bg-shell-card-subtle'
                  }`}>
                  <div className="flex items-start gap-2.5">
                    <div className={`w-10 h-10 rounded-xl overflow-hidden border flex items-center justify-center shrink-0 ${cancelled ? 'border-red-200 bg-white' : 'border-shell-border bg-white'}`}>
                      {a.patient_photo ? (
                        <img src={a.patient_photo} alt="" className="w-full h-full object-cover" />
                      ) : (
                        <User className={`w-4 h-4 ${cancelled ? 'text-red-400' : 'text-ink-secondary'}`} />
                      )}
                    </div>
                    <div className="min-w-0 flex-1">
                      <div className="flex items-center justify-between gap-2">
                        <span className={`text-[10px] font-bold font-mono ${cancelled ? 'text-red-600' : 'text-teal-brand'}`}>{a.id}</span>
                        <span className={`text-[9px] font-bold px-1.5 py-0.5 rounded-full border ${
                          cancelled
                            ? 'bg-red-100 text-red-700 border-red-300'
                            : a.status === 'COMPLETED'
                            ? 'bg-pastel-mint-bg text-pastel-mint-text border-pastel-mint-border'
                            : a.status === 'CONFIRMED'
                            ? 'bg-teal-brand/10 text-teal-brand border-teal-brand/20'
                            : 'bg-amber-50 text-amber-800 border-amber-200'
                        }`}>{a.status}</span>
                      </div>
                      <p className={`text-xs font-bold ${cancelled ? 'text-red-900' : 'text-ink-primary'}`}>{a.hospital_name}</p>
                      <p className={`text-[11px] ${cancelled ? 'text-red-700/80' : 'text-ink-secondary'}`}>
                        {a.doctor_name} · {a.date} {formatTime12(a.time)} · Age {a.patient_age_group}
                      </p>
                    </div>
                  </div>

                  <div className="flex flex-wrap items-center gap-2 mt-1">
                    <a href={a.hospital_map_url} target="_blank" rel="noopener noreferrer"
                      className={`text-[10px] font-semibold flex items-center gap-1 ${cancelled ? 'text-red-600' : 'text-teal-brand'}`}>
                      <MapPin className="w-3 h-3" /> Map
                    </a>
                    <button type="button" onClick={() => setExpandedAppt(open ? null : a.id)}
                      className={`text-[10px] font-semibold ${cancelled ? 'text-red-700' : 'text-ink-secondary'} hover:underline`}>
                      {open ? 'Hide details' : 'Prescription & bill'}
                    </button>
                  </div>

                  {open && (
                    <div className={`mt-2 rounded-xl border p-3 space-y-2 ${cancelled ? 'border-red-200 bg-white' : 'border-shell-border bg-white'}`}>
                      <div className="flex items-center justify-between">
                        <p className="text-[11px] font-bold text-ink-primary flex items-center gap-1">
                          <IndianRupee className="w-3.5 h-3.5" /> Total bill
                        </p>
                        <p className="text-sm font-bold text-ink-primary">₹{a.total_bill_inr.toLocaleString('en-IN')}</p>
                      </div>
                      <div>
                        <p className="text-[11px] font-bold text-ink-primary flex items-center gap-1 mb-1">
                          <FileText className="w-3.5 h-3.5" /> Prescription
                        </p>
                        {a.prescription ? (
                          <ul className="text-[11px] text-ink-secondary space-y-0.5">
                            {a.prescription.medicines.map((m, i) => (
                              <li key={i}>{m.name} — {m.dosage} — {m.duration}</li>
                            ))}
                            <li className="italic mt-1">{a.prescription.advice}</li>
                          </ul>
                        ) : (
                          <p className="text-[11px] text-ink-secondary">Prescription will appear after the doctor completes the visit.</p>
                        )}
                      </div>
                      <div>
                        <p className="text-[11px] font-bold text-ink-primary flex items-center gap-1 mb-1">
                          <CalendarClock className="w-3.5 h-3.5" /> Re-appointment
                        </p>
                        {a.reappointment_date ? (
                          <p className="text-[11px] text-ink-secondary">
                            Allotted by doctor: {a.reappointment_date}
                            {a.reappointment_time ? ` · ${formatTime12(a.reappointment_time)}` : ''}
                            {a.reappointment_note ? ` — ${a.reappointment_note}` : ''}
                          </p>
                        ) : (
                          <p className="text-[11px] text-ink-secondary">No follow-up allotted yet.</p>
                        )}
                      </div>
                      <button type="button" onClick={() => downloadPrescriptionPdf(a)}
                        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-[10px] font-bold bg-teal-brand text-white">
                        <Download className="w-3 h-3" /> Download prescription PDF
                      </button>
                    </div>
                  )}
                </div>
              );
            })}
          </div>
          )}
        </div>
      )}
    </div>
  );
};
